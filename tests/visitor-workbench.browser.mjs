import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.VISITOR_PREVIEW_URL || 'http://127.0.0.1:3110';
const output = new URL('../test-artifacts/visitor-workbench/', import.meta.url).pathname;
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
let checks = 0;
try {
  for (const width of [1440, 768, 390, 320]) {
    const context = await browser.newContext({ viewport: { width, height: 950 }, permissions: ['clipboard-read', 'clipboard-write'] });
    const page = await context.newPage(); const errors = [], apiWrites = [];
    page.setDefaultTimeout(15000);
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', req => { if (req.method() === 'POST' && req.url().includes('/api/')) apiWrites.push(req.url()); });
    await page.goto(`${base}/admin/visitor-preview`, { waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: 'Classification evidence', exact: true }).first().waitFor();
    assert.ok(await page.getByText('Local preview · Sample data', { exact: true }).isVisible());
    const toolbar = page.getByRole('region', { name: 'Visitor view options' });
    const zone = toolbar.getByRole('group', { name: 'Display time zone' });
    await zone.getByRole('button', { name: 'UTC', exact: true }).click();
    assert.equal(await zone.getByRole('button', { name: 'UTC', exact: true }).getAttribute('aria-pressed'), 'true');
    assert.equal(await zone.getByRole('button', { name: 'Local', exact: true }).getAttribute('aria-pressed'), 'false');
    assert.ok(await toolbar.getByLabel('Saved filter views').isDisabled());
    assert.ok(await toolbar.getByRole('button', { name: 'Save view', exact: true }).isDisabled());
    const geometry = await toolbar.evaluate(el => {
      const rect = node => { const r = node.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; };
      return { bounds: rect(el), controls: [...el.querySelectorAll('input, select, button')].map(rect), rows: [...el.children].map(child => rect(child)) };
    });
    for (const control of geometry.controls) {
      assert.ok(control.x >= geometry.bounds.x - 1 && control.x + control.width <= geometry.bounds.x + geometry.bounds.width + 1, `Toolbar control overflow at ${width}`);
    }
    if (width === 1440) {
      assert.ok(geometry.rows.every(row => Math.abs(row.y - geometry.rows[0].y) < 1), 'Desktop fields align');
      const switchBox = await zone.boundingBox(), selectBox = await toolbar.getByLabel('Saved filter views').boundingBox();
      const inputBox = await toolbar.getByLabel('New view name').boundingBox();
      assert.equal(switchBox.y, selectBox.y, 'Timezone and saved-view controls align');
      assert.equal(inputBox.y, selectBox.y, 'All desktop control baselines align');
      assert.equal(switchBox.height, selectBox.height, 'Timezone and inputs have equal heights');
    } else if (width < 540) assert.ok(geometry.rows[1].y >= geometry.rows[0].y + geometry.rows[0].height, 'Mobile fields stack');
    const savedSelect = await toolbar.getByLabel('Saved filter views').boundingBox();
    const deleteButton = await toolbar.getByRole('button', { name: 'Delete selected view' }).boundingBox();
    assert.equal(savedSelect.y, deleteButton.y, 'Saved-view actions align');
    assert.equal(savedSelect.height, deleteButton.height, 'Saved-view controls have equal heights');
    const card = page.locator('article').filter({ hasText: 'Jaipur' }).first();
    await card.scrollIntoViewIfNeeded();
    const map = card.getByRole('link', { name: /Jaipur/ });
    assert.match(await map.getAttribute('href'), /maps\/search\/\?api=1&query=Jaipur/);
    assert.equal(await map.getAttribute('target'), '_blank');
    assert.equal(await card.getByRole('link', { name: 'Open source website' }).getAttribute('href'), 'https://linkedin.com');
    await card.getByRole('button', { name: 'Copy IP address', exact: true }).click();
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), '198.51.100.24');
    await card.getByRole('button', { name: 'Filter this city' }).click();
    assert.equal(await page.getByLabel('City', { exact: true }).inputValue(), 'Jaipur');
    assert.equal(await page.getByLabel('Country', { exact: true }).inputValue(), 'IN');
    await page.getByLabel('New view name').fill('Jaipur mobile');
    await page.getByRole('button', { name: 'Save view', exact: true }).click();
    assert.equal(await page.getByLabel('Saved filter views').inputValue(), 'Jaipur mobile');
    assert.equal(await page.getByLabel('New view name').inputValue(), '');
    await page.getByRole('button', { name: 'Reset filters', exact: true }).click();
    await page.getByLabel('Saved filter views').selectOption('Jaipur mobile');
    assert.equal(await page.getByLabel('City', { exact: true }).inputValue(), 'Jaipur');
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByLabel('Saved filter views').selectOption('Jaipur mobile');
    const view = page.getByRole('group', { name: 'Visitor record view' });
    assert.equal(await view.getByRole('button', { name: 'Page visits', exact: true }).getAttribute('aria-pressed'), 'true');
    await view.getByRole('button', { name: 'Raw events', exact: true }).click();
    await page.getByText(/of \d+ events · Page/).first().waitFor();
    const rawCount = await page.locator('article').count();
    await view.getByRole('button', { name: 'Page visits', exact: true }).click();
    await page.waitForFunction(count => document.querySelectorAll('article').length === count - 18, rawCount);
    const row = page.locator('article').filter({ hasText: 'Jaipur' }).first();
    assert.ok(await row.getByTitle('Approximate furthest scroll checkpoint on this page, not proof that the content was read.').getByText('About 100%', { exact: true }).isVisible());
    assert.ok(await row.getByText('25% / 50% / 75% / 100%', { exact: true }).isVisible());
    await row.locator('details').filter({ hasText: '25% / 50% / 75% / 100%' }).locator('summary').click();
    assert.equal(await row.locator('details[open] li').count(), 4);
    await row.screenshot({ path: `${output}/${width}-grouped-visit.png` });
    await row.getByRole('button', { name: 'Timeline', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Session details' });
    await dialog.getByText('11 activities in window from 29 recorded events.', { exact: false }).waitFor();
    assert.equal(await dialog.locator('ol > li').count(), 11);
    assert.ok(await dialog.getByRole('button', { name: 'Next', exact: true }).isDisabled());
    const checkpoint = dialog.locator('details').filter({ hasText: '25% / 50% / 75% / 100%' });
    await checkpoint.locator('summary').click();
    await checkpoint.scrollIntoViewIfNeeded();
    assert.equal(await checkpoint.locator('li').count(), 4);
    assert.equal(await dialog.evaluate(el => el.scrollWidth > el.clientWidth + 1), false, `Timeline overflow at ${width}`);
    await page.screenshot({ path: `${output}/${width}-grouped-timeline.png` });
    await dialog.getByRole('tab', { name: 'MCP analysis' }).click();
    await dialog.getByText('Partial evidence only.', { exact: false }).waitFor();
    assert.ok(await dialog.getByText('Not performed', { exact: true }).isVisible());
    await page.screenshot({ path: `${output}/${width}-analysis.png` });
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();
    await dialog.getByText('Page 2', { exact: true }).waitFor();
    await dialog.getByRole('tab', { name: 'Timeline', exact: true }).click();
    await dialog.getByText('11 activities in window from 29 recorded events.', { exact: false }).waitFor();
    assert.ok(await dialog.getByText('Page 1', { exact: true }).isVisible());
    await dialog.getByRole('tab', { name: 'Classification', exact: true }).click();
    assert.ok(await dialog.getByText('Not classified as a bot', { exact: true }).isVisible());
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(), 0);
    await row.getByRole('button', { name: 'Create alert', exact: true }).click();
    const editor = page.getByRole('dialog', { name: 'Create alert rule' });
    assert.equal(await editor.getByLabel('Scope ID', { exact: true }).inputValue(), 'REGION:IN:RJ');
    assert.equal(await editor.getByLabel('Referrer domain (exact)', { exact: true }).inputValue(), 'linkedin.com');
    assert.equal(await editor.getByLabel('Traffic classification', { exact: true }).inputValue(), 'EXCLUDE');
    await editor.getByLabel('Change reason').fill('Local interaction test');
    await editor.getByRole('button', { name: 'Review changes', exact: true }).click();
    const review = page.getByRole('alertdialog'); await review.waitFor();
    assert.ok(await review.getByText(/linkedin.com/).isVisible());
    assert.equal(await review.evaluate(el => el.scrollWidth > el.clientWidth + 1), false, `Review overflow at ${width}`);
    await page.screenshot({ path: `${output}/${width}-alert-review.png` });
    await review.getByRole('button', { name: 'Apply changes', exact: true }).click();
    await review.waitFor({ state: 'hidden' });
    await page.getByTitle('Collapse behavior alerts', { exact: true }).click();
    await page.getByLabel('Saved filter views').selectOption('Jaipur mobile');
    await page.getByRole('button', { name: 'Delete selected view' }).click();
    assert.equal(await page.getByLabel('Saved filter views').locator('option').count(), 1);
    assert.ok(await page.getByLabel('Saved filter views').isDisabled());
    await page.getByRole('button', { name: 'Reset filters', exact: true }).click();
    await page.locator('article').first().getByRole('button', { name: 'Classification evidence' }).click();
    assert.ok(await page.getByRole('dialog').getByText('0.1 / 1 (higher means more human-like)').isVisible());
    await page.keyboard.press('Escape');
    await toolbar.scrollIntoViewIfNeeded();
    await toolbar.screenshot({ path: `${output}/${width}-toolbar.png` });
    await page.locator('article').first().scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${output}/${width}-records.png` });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    assert.equal(overflow, false, `Horizontal overflow at ${width}`);
    assert.deepEqual(errors, []); assert.deepEqual(apiWrites, []);
    checks++; console.log(`PASS ${width}px: filters, maps, copy, saved views, timeline pagination, MCP evidence, alert review, no live writes`);
    await context.close();
  }
  console.log(`${checks} viewport scenarios passed. Screenshots: ${output}`);
} catch (error) { console.error(error); throw error; }
finally { await browser.close(); }
